-- Cinema FMI: structura bazei de date cinemadb.
-- Rulati scriptul in pgAdmin (Query Tool), pe baza cinemadb.
-- Il puteti rula oricand din nou: sterge tabelele si le creeaza de la zero.

DROP TABLE IF EXISTS screenings;
DROP TABLE IF EXISTS movies;

CREATE TABLE movies (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(40)  NOT NULL,
    genre VARCHAR(30)  NOT NULL,
    price NUMERIC(6, 2) NOT NULL CHECK (price > 0)
);

-- O proiectie apartine unui film: movie_id este cheie straina (foreign key) catre movies.id.
CREATE TABLE screenings (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id   BIGINT      NOT NULL REFERENCES movies (id),
    start_time VARCHAR(5)  NOT NULL,
    room       VARCHAR(20) NOT NULL,
    seats_left INT         NOT NULL CHECK (seats_left >= 0)
);
